import { describe, expect, it } from 'vitest'
import { buildMeetingKey, channelFromModeName, formatSummaryForPost } from '../../shared/summaryPublish'

describe('channelFromModeName', () => {
  it('lowercases the mode name and turns spaces into dashes', () => {
    expect(channelFromModeName('HRM Daily')).toBe('hrm-daily')
  })

  it('trims the name and collapses runs of spaces', () => {
    expect(channelFromModeName('  CVM   Daily  ')).toBe('cvm-daily')
  })

  it('keeps non-latin names', () => {
    expect(channelFromModeName('Груминг PIM')).toBe('груминг-pim')
  })
})

describe('buildMeetingKey', () => {
  it('joins the channel and the local date of the session', () => {
    const startedAt = new Date(2026, 9, 14, 9, 30).getTime()
    expect(buildMeetingKey('hrm-daily', startedAt)).toBe('hrm-daily:2026-10-14')
  })

  it('zero-pads month and day', () => {
    const startedAt = new Date(2026, 0, 5, 23, 59).getTime()
    expect(buildMeetingKey('cvm-daily', startedAt)).toBe('cvm-daily:2026-01-05')
  })
})

describe('formatSummaryForPost', () => {
  it('sends every section, Action items included', () => {
    const summary = [
      '## Итоги груминга PIM',
      '',
      '## Конструктор свойств',
      '* Решение: взять в работу',
      '',
      '### Детали',
      'Текст',
      '',
      '## Action items',
      '- Написать Саше',
    ].join('\n')
    expect(formatSummaryForPost(summary, 'GLM-5.3 Flash')).toBe(
      [
        '##### Итоги груминга PIM (generated by GLM-5.3 Flash)',
        '',
        '##### Конструктор свойств',
        '* Решение: взять в работу',
        '',
        '##### Детали',
        'Текст',
        '',
        '##### Action items',
        '- Написать Саше',
      ].join('\n'),
    )
  })

  it('titles leading plain text as Summary', () => {
    expect(formatSummaryForPost('Recap.\n\n# Key points\n- One', 'GLM-5.3 Flash')).toBe(
      ['##### Summary (generated by GLM-5.3 Flash)', '', 'Recap.', '', '##### Key points', '- One'].join('\n'),
    )
  })

  it('adds no parentheses when the model is unknown', () => {
    expect(formatSummaryForPost('#### Summary\nText', null)).toBe('##### Summary\nText')
  })

  it('returns an empty string when there is no summary', () => {
    expect(formatSummaryForPost('  \n')).toBe('')
    expect(formatSummaryForPost(null)).toBe('')
  })
})
