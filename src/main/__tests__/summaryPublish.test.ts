import { describe, expect, it } from 'vitest'
import { buildMeetingKey, extractPublishableSummary, isSummaryChannel } from '../../shared/summaryPublish'

describe('isSummaryChannel', () => {
  it('accepts only the known channels', () => {
    expect(isSummaryChannel('cvm-daily')).toBe(true)
    expect(isSummaryChannel('hrm-daily')).toBe(true)
    expect(isSummaryChannel('pim-daily')).toBe(true)
    expect(isSummaryChannel('other')).toBe(false)
    expect(isSummaryChannel(undefined)).toBe(false)
  })
})

describe('buildMeetingKey', () => {
  it('joins the channel and the local date of the session', () => {
    const startedAt = new Date(2026, 9, 14, 9, 30).getTime()
    expect(buildMeetingKey('hrm-daily', startedAt)).toBe('hrm-daily:2026-10-14')
  })

  it('zero-pads month and day', () => {
    const startedAt = new Date(2026, 0, 5, 23, 59).getTime()
    expect(buildMeetingKey('cvm-daily', startedAt)).toBe('cvm-daily:2026-01-05')
  })
})

describe('extractPublishableSummary', () => {
  it('keeps the leading prose and Key points, drops Action items', () => {
    const summary = [
      'Обсудили метрики.',
      '',
      'Второй абзац.',
      '',
      '## Key points',
      '',
      '- Пункт один',
      '',
      '## Action items',
      '',
      '- **Антон** — завести задачи',
    ].join('\n')

    expect(extractPublishableSummary(summary)).toBe(
      ['##### Summary', 'Обсудили метрики.', '', 'Второй абзац.', '', '##### Key points', '- Пункт один'].join('\n'),
    )
  })

  it('keeps an explicit Summary section and drops other sections', () => {
    const summary = [
      '## Summary',
      'Text',
      '### Decisions',
      '- Ship it',
      '## **Key Points:**',
      '- One',
      '## Open questions',
      '- Why',
    ].join('\n')

    expect(extractPublishableSummary(summary)).toBe(['##### Summary', 'Text', '', '##### Key Points', '- One'].join('\n'))
  })

  it('keeps the first section whatever its title, e.g. a Russian recap heading', () => {
    const summary = [
      '## Основные итоги',
      '- **HRM-913** выкатывается сегодня',
      '',
      '## Key Points',
      '- Сначала бэк, затем фронт',
      '',
      '## Action items',
      '- **Илья** — описать API',
    ].join('\n')

    expect(extractPublishableSummary(summary, 'GLM-5.3 Flash')).toBe(
      [
        '##### Основные итоги (generated by GLM-5.3 Flash)',
        '- **HRM-913** выкатывается сегодня',
        '',
        '##### Key Points',
        '- Сначала бэк, затем фронт',
      ].join('\n'),
    )
  })

  it('does not treat a later free-form section as the summary when prose leads', () => {
    expect(extractPublishableSummary('Recap.\n\n## Решения\n- One\n## Key points\n- Two')).toBe(
      ['##### Summary', 'Recap.', '', '##### Key points', '- Two'].join('\n'),
    )
  })

  it('sends every title as #####, whatever level the notes used', () => {
    expect(extractPublishableSummary('# Summary\nText\n#### Key points\n- One')).toBe(
      ['##### Summary', 'Text', '', '##### Key points', '- One'].join('\n'),
    )
  })

  it('titles plain prose as Summary even without other sections', () => {
    expect(extractPublishableSummary('Just a recap.\n')).toBe('##### Summary\nJust a recap.')
  })

  it('names the model in the first title only', () => {
    expect(extractPublishableSummary('Recap.\n\n## Key points\n- One', 'GLM-5.3 Flash')).toBe(
      ['##### Summary (generated by GLM-5.3 Flash)', 'Recap.', '', '##### Key points', '- One'].join('\n'),
    )
    expect(extractPublishableSummary('## Summary\nText', 'Claude Haiku 4.5')).toBe(
      '##### Summary (generated by Claude Haiku 4.5)\nText',
    )
  })

  it('adds no parentheses when the model is unknown', () => {
    expect(extractPublishableSummary('Recap.', null)).toBe('##### Summary\nRecap.')
  })

  it('returns an empty string when nothing publishable is left', () => {
    expect(extractPublishableSummary('## Action items\n- Do it')).toBe('')
    expect(extractPublishableSummary(null)).toBe('')
  })
})
