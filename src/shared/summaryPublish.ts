/**
 * Publishing a session summary to Mattermost via an n8n webhook: the
 * channels the user can pick (set in Settings → Integrations), the meeting
 * key n8n groups posts by, and how the summary is formatted for the post.
 */

/**
 * The channels saved in settings (`n8nChannels`), trimmed, without blanks
 * or duplicates. Accepts a string too, one channel per line or comma.
 */
export function parseSummaryChannels(value: unknown): string[] {
  const items = Array.isArray(value) ? value : typeof value === 'string' ? value.split(/[\n,]/) : []
  const channels: string[] = []
  for (const item of items) {
    if (typeof item !== 'string') continue
    const channel = item.trim()
    if (channel && !channels.includes(channel)) channels.push(channel)
  }
  return channels
}

/** "<channel>:YYYY-MM-DD", using the local date the session started. */
export function buildMeetingKey(channel: string, startedAt: number): string {
  const date = new Date(startedAt)
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${channel}:${date.getFullYear()}-${month}-${day}`
}

const HEADING = /^#{1,6}\s+(.*)$/

/**
 * The whole summary as generated, ready to post. Only the headings change:
 * they are sent as #####, because Mattermost renders #### and above larger
 * than wanted, and the first one names the model, e.g.
 * "##### Итоги груминга PIM (generated by GLM-5.3 Flash)". Notes that open
 * with plain text get a "##### Summary" title to carry the model name.
 */
export function formatSummaryForPost(summary: string | null | undefined, model?: string | null): string {
  const text = (summary ?? '').trim()
  if (!text) return ''
  const suffix = model?.trim() ? ` (generated by ${model.trim()})` : ''
  const lines = text.split('\n')
  if (!HEADING.test(lines[0])) lines.unshift('##### Summary', '')
  let named = false
  return lines
    .map((line) => {
      const heading = line.match(HEADING)
      if (!heading) return line
      const title = `##### ${heading[1].trim()}${named ? '' : suffix}`
      named = true
      return title
    })
    .join('\n')
}
