/**
 * Publishing a session summary to Mattermost via an n8n webhook: the
 * channels the user can pick (set in Settings → Integrations), the meeting
 * key n8n groups posts by, and which parts of the summary are sent.
 */

/**
 * The channels saved in settings (`n8nChannels`), trimmed, without blanks
 * or duplicates. Accepts a string too, one channel per line or comma.
 */
export function parseSummaryChannels(value: unknown): string[] {
  const items = Array.isArray(value) ? value : typeof value === 'string' ? value.split(/[\n,]/) : []
  const channels: string[] = []
  for (const item of items) {
    if (typeof item !== 'string') continue
    const channel = item.trim()
    if (channel && !channels.includes(channel)) channels.push(channel)
  }
  return channels
}

/** "<channel>:YYYY-MM-DD", using the local date the session started. */
export function buildMeetingKey(channel: string, startedAt: number): string {
  const date = new Date(startedAt)
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${channel}:${date.getFullYear()}-${month}-${day}`
}

const HEADING = /^(#{1,6})\s+(.*)$/
const PUBLISHABLE_HEADING = /^(summary|key\s+points?)$/i
const ACTION_ITEMS_HEADING = /^action\s+items?$/i

/**
 * Only the summary and "Key points" are published; Action items and any
 * other sections stay in the app. The summary is the text before the first
 * heading, or else the first section whatever its title: the notes prompt
 * lets the model name headings, so it may be "Основные итоги" rather than
 * "Summary". When that first heading is a bare title with no text of its
 * own (e.g. "# Итоги груминга HRM"), the recap lives in its subsections, so
 * the deeper headings under it are kept too, except Action items.
 * Untitled leading prose gets a "Summary" title so the post reads
 * the same as the sections after it. Titles are sent as #####, because
 * Mattermost renders #### and above larger than wanted; the first one names
 * the model, e.g. "##### Summary (generated by GLM-5.3 Flash)".
 */
export function extractPublishableSummary(
  summary: string | null | undefined,
  model?: string | null,
): string {
  type Section = { title: string; level: number; body: string[] }
  const preamble: string[] = []
  const sections: Section[] = []
  let current: Section | null = null
  let lead: Section | null = null
  // Level of the leading heading once it proves to be a bare title.
  let titleLevel: number | null = null
  for (const line of (summary ?? '').split('\n')) {
    const heading = line.match(HEADING)
    if (heading) {
      const level = heading[1].length
      const title = heading[2].replace(/\*\*/g, '').replace(/:\s*$/, '').trim()
      if (lead && current === lead && !lead.body.join('').trim()) titleLevel = lead.level
      const leadsSummary: boolean =
        current === null && !preamble.join('').trim() && !ACTION_ITEMS_HEADING.test(title)
      const underTitle: boolean = titleLevel !== null && level > titleLevel && !ACTION_ITEMS_HEADING.test(title)
      const keep: boolean = leadsSummary || underTitle || PUBLISHABLE_HEADING.test(title)
      current = { title: keep ? title : '', level, body: [] }
      if (leadsSummary) lead = current
      if (current.title) sections.push(current)
      continue
    }
    if (current) current.body.push(line)
    else preamble.push(line)
  }
  const prose = preamble.join('\n').trim()
  if (prose) sections.unshift({ title: 'Summary', level: 0, body: [prose] })
  const suffix = model?.trim() ? ` (generated by ${model.trim()})` : ''
  return sections
    .map((section, index) => {
      const title = `##### ${section.title}${index === 0 ? suffix : ''}`
      const body = section.body.join('\n').trim()
      return body ? `${title}\n${body}` : title
    })
    .join('\n\n')
}
